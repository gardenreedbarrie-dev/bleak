#!/usr/bin/env python3
# The battleground kill announcer's voice lines (docs/BleakholdProtocol.md section 18, Announcer.lua).
#
#   python3 -I Tools/Announcer/import_sounds.py [--from DIR] [--check]
#
#   --from DIR  first copy DIR/<set>/<line>.wav into Interface/AddOns/Bleakhold/Sounds/Announcer/<set>/ for every
#               set (male, female, male_quiet, female_quiet) and line below; every file must be there
#   --check     write nothing: exit 1 when AnnouncerData.lua does not match the WAV files
#
# Then it reads every WAV of the addon (16-bit PCM, mono or stereo, any rate; anything else is an error) and writes
# Interface/AddOns/Bleakhold/AnnouncerData.lua: each line's real length in seconds, rounded up to the millisecond. The
# addon waits that long before the next line, because 3.3.5a cannot stop a sound. Rerun it whenever a WAV changes;
# Tools/UiLint/tests/test_announcer.lua fails while the table and the files disagree.
import argparse
import math
import os
import shutil
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
ADDON = os.path.join(ROOT, "Interface", "AddOns", "Bleakhold")
SOUNDS = os.path.join(ADDON, "Sounds", "Announcer")
OUT = os.path.join(ADDON, "AnnouncerData.lua")

SETS = ["male", "female", "male_quiet", "female_quiet"]
LINES = ["firstblood", "doublekill", "triplekill", "ultrakill", "rampage", "killingspree", "dominating", "megakill",
         "unstoppable", "wickedsick", "monsterkill", "godlike", "holyshit"]


def wav_seconds(path):
    """Length of a PCM WAV in seconds, from its fmt and data chunks."""
    with open(path, "rb") as fh:
        data = fh.read()
    if len(data) < 12 or data[0:4] != b"RIFF" or data[8:12] != b"WAVE":
        raise ValueError("%s: not a RIFF/WAVE file" % path)
    pos, fmt, size = 12, None, None
    while pos + 8 <= len(data):
        cid, clen = data[pos:pos + 4], struct.unpack("<I", data[pos + 4:pos + 8])[0]
        body = data[pos + 8:pos + 8 + clen]
        if cid == b"fmt ":
            fmt = struct.unpack("<HHIIHH", body[:16])
        elif cid == b"data":
            size = min(clen, len(data) - pos - 8)
        pos += 8 + clen + (clen & 1)
    if not fmt or size is None:
        raise ValueError("%s: no fmt or data chunk" % path)
    tag, channels, rate, _, align, bits = fmt
    if tag != 1 or bits != 16 or channels not in (1, 2) or rate <= 0 or align != channels * 2:
        raise ValueError("%s: needs 16-bit PCM, mono or stereo (format %d, %d bit, %d channels)"
                         % (path, tag, bits, channels))
    return (size // align) / rate


def render():
    out = ["-- Bleakhold: the kill announcer's voice line lengths in seconds (Announcer.lua), per set and line.",
           "-- Generated by Tools/Announcer/import_sounds.py from Sounds/Announcer/<set>/<line>.wav. Do not edit:",
           "-- rerun the script after changing a WAV (Tools/UiLint/tests/test_announcer.lua checks the two agree).",
           "local ADDON, ns = ...", "", "ns.ANNOUNCER_SECONDS = {"]
    for s in SETS:
        out.append("    %s = {" % s)
        for line in LINES:
            path = os.path.join(SOUNDS, s, line + ".wav")
            ms = math.ceil(wav_seconds(path) * 1000 - 1e-9)
            out.append("        %s = %d.%03d," % (line, ms // 1000, ms % 1000))
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--from", dest="src")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.src and a.check:
        ap.error("--from and --check do not go together")
    if a.src:
        missing = [os.path.join(s, l + ".wav") for s in SETS for l in LINES
                   if not os.path.isfile(os.path.join(a.src, s, l + ".wav"))]
        if missing:
            print("import_sounds: missing in %s: %s" % (a.src, ", ".join(missing)), file=sys.stderr)
            return 1
        for s in SETS:
            os.makedirs(os.path.join(SOUNDS, s), exist_ok=True)
            for line in LINES:
                src = os.path.join(a.src, s, line + ".wav")
                wav_seconds(src)   # refuse a file the client cannot play before copying anything over
                shutil.copyfile(src, os.path.join(SOUNDS, s, line + ".wav"))
    try:
        text = render()
    except (OSError, ValueError) as e:
        print("import_sounds: %s" % e, file=sys.stderr)
        return 1
    if a.check:
        old = open(OUT, "r", encoding="utf-8").read() if os.path.isfile(OUT) else ""
        if old != text:
            print("import_sounds: AnnouncerData.lua is out of date (run python3 -I Tools/Announcer/import_sounds.py)",
                  file=sys.stderr)
            return 1
        print("AnnouncerData.lua matches the WAV files")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d sets x %d lines)" % (os.path.relpath(OUT, ROOT), len(SETS), len(LINES)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
