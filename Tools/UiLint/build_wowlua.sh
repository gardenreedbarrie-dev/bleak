#!/usr/bin/env bash
# Build 'wowlua', a native Linux host for the client's own Lua 5.1 (Engine/Source/lua-5.1/src).
#
#   Tools/UiLint/build_wowlua.sh [outdir]      (default outdir: Tools/UiLint/build)
#
# The Lua sources are compiled as C++ with g++, exactly as the client compiles them, with a small shim
# (host/shim.h, host/stubs.cpp) for the engine functions they call. sgetu8/sputu8 are copied out of
# Engine/Source/Base/ConvertUTF.cpp so string.upper/lower behave like the client. lmemPool.cpp (Storm
# allocator) is left out; the host uses Lua's default allocator.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../.." && pwd)"
out="${1:-$here/build}"
src="$root/Engine/Source/lua-5.1/src"
cxx="${CXX:-g++}"

mkdir -p "$out/obj"

# Copy sgetu8 and sputu8 (each runs from its signature line to the first line that is just "}").
utf="$out/obj/convertutf_copy.cpp"
{
    echo '// Generated by build_wowlua.sh from Engine/Source/Base/ConvertUTF.cpp. Do not edit.'
    echo '#include <cstdint>'
    awk '/^uint32_t sgetu8\(|^char\* sputu8\(/ { on = 1 } on { print } on && /^}/ { on = 0; print "" }' \
        "$root/Engine/Source/Base/ConvertUTF.cpp"
} > "$utf"
grep -q '^uint32_t sgetu8(' "$utf" || { echo "build_wowlua: sgetu8 not found in ConvertUTF.cpp" >&2; exit 1; }
grep -q '^char\* sputu8(' "$utf" || { echo "build_wowlua: sputu8 not found in ConvertUTF.cpp" >&2; exit 1; }

flags=(-x c++ -std=c++17 -O1 -w -fno-strict-aliasing -I"$root" -I"$src" -include "$here/host/shim.h")
objs=()
for f in "$src"/*.c; do
    o="$out/obj/$(basename "${f%.c}").o"
    if [[ ! -f "$o" || "$f" -nt "$o" || "$here/host/shim.h" -nt "$o" ]]; then
        "$cxx" "${flags[@]}" -c "$f" -o "$o"
    fi
    objs+=("$o")
done
"$cxx" -std=c++17 -O1 -w -I"$root" -I"$src" -include "$here/host/shim.h" \
    "$here/host/main.cpp" "$here/host/stubs.cpp" "$utf" "${objs[@]}" -lm -o "$out/wowlua"

# Self-check: the host must parse, run, and have bit but no print-less surprises.
probe="$out/obj/probe.lua"
printf 'assert(bit and bit.band(6,3)==2)\nassert(not os and not io and not debug)\nassert(string.upper("abc")=="ABC")\nprint("wowlua ok")\n' > "$probe"
"$out/wowlua" "$probe"
