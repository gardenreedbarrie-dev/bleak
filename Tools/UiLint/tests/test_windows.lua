test("Dungeons: board, tiers, bounty, double Shards, queue flow with level band", function(M, ns)
    FX.connect(M, H)
    FX.all(M, H)
    ns.UI.Open("dungeons")
    M.Advance(0.5)
    local P = ns.Dungeons
    H.ok(texts(M, "Chapter I - Old Kingdoms") > 0, "chapter header")
    H.ok(texts(M, "Ragefire Chasm") > 0, "dungeon row")
    H.ok(texts(M, "Server record 2,400 - Aldric") > 0, "server record")
    H.ok(texts(M, "Double Shards") > 0, "first run marker")
    H.ok(texts(M, "1,260") > 0, "shards")
    H.ok(P.bountyClaim:IsShown(), "bounty claim")
    P.bountyClaim:Click()
    H.eq(H.lastIntent(M, "BCLAIM").payload, "55")
    -- tier not unlocked -> join disabled
    P.selected = 602
    P.tier = 1
    P:Refresh()
    H.ok(not P.queue.join:IsEnabled(), "locked dungeon cannot be queued")
    P.selected = 389
    P.tierButtons[3]:Click()
    P.sizeButtons[3]:Click()
    P.queue.join:Click()
    H.eq(H.lastIntent(M, "QJOIN").payload, "D,389,2,4,3")
    H.send(M, "QUEUE", { { 2, 1, "D", 389, 2, 3, 30, 300, "", "", 13, 18 } })
    H.ok(texts(M, "Matching levels 13-18") > 0, "level band from the server")
    M.Advance(2)
    H.ok(texts(M, "Waiting 00:3") > 0, "queue timer counts")
    P.queue.join:Click()
    H.ok(H.lastIntent(M, "QLEAVE"), "leave")
    H.send(M, "QUEUE", FX.examples(M).QUEUE)
    H.ok(P.queue.accept:IsShown(), "proposal")
    H.ok(texts(M, "Brenna") > 0, "members")
    P.queue.accept:Click()
    H.eq(H.lastIntent(M, "QREPLY").payload, "77,1")
    P.queue.decline:Click()
    H.eq(H.lastIntent(M, "QREPLY").payload, "77,0")
    -- Eclipse Rift queue
    H.send(M, "QUEUE", { { 9, 0 } })
    P.queue.rift:Click()
    P.queue.join:Click()
