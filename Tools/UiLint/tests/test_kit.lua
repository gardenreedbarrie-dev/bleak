-- The kit (Widgets.lua) in the stock 3.3.5a look: the windows' chrome, the stock text colours, the red panel button
-- and its states, tabs, ring portraits with the icon fallback, the backdrop looks, the scroll bar, the dropdown and
-- the dialog. These pin what the WoW look is built from, so a page cannot drift back to the flat custom kit.

local GOLD = { 1, 0.82, 0 }

local function near(a, b)
    return math.abs(a - b) < 0.01
end

-- colorIs(want, what, r, g, b): the colour call goes last so all its values arrive
local function colorIs(want, what, r, g, b)
    H.ok(near(r, want[1]) and near(g, want[2]) and near(b, want[3]),
        what .. ": " .. table.concat({ r, g, b }, ",") .. " is not " .. table.concat(want, ","))
end

